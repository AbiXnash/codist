package review

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"codist/internal/gitx"
)

// Lessons turn this repository's own history into knowledge the reviewer retrieves (see the
// knowledge package): issues that were fixed become worked examples with the real before and after
// code, and findings the team dismissed become "not a problem here" notes, so the model learns what
// matters in this codebase and stops repeating false alarms. The file is rebuilt from the tracker,
// so it always matches the current history (a revert removes its lesson).
type Lessons struct {
	repo    *gitx.Repo
	tracker *Tracker
	ignores *Ignores
	dir     string // <data-dir>/<repo>/lessons
}

func NewLessons(repo *gitx.Repo, tracker *Tracker, ignores *Ignores, dataDir string) *Lessons {
	return &Lessons{repo: repo, tracker: tracker, ignores: ignores, dir: filepath.Join(dataDir, repo.Name(), "lessons")}
}

const maxLessons = 150

// Write rebuilds lessons.md; it only touches the file when the content changed (the knowledge base
// reloads on change).
func (l *Lessons) Write() (int, error) {
	var b strings.Builder
	b.WriteString("# Learned in this codebase\n\nGenerated by Codist from this repository's history. Do not edit: it is rebuilt.\n\n")
	n := 0
	issues := l.tracker.Issues()
	sort.SliceStable(issues, func(i, j int) bool { return issues[i].FixedAt > issues[j].FixedAt })
	seen := map[string]bool{}
	for _, is := range issues {
		if n >= maxLessons {
			break
		}
		if is.State != "resolved" || is.FixedIn == "" || seen[is.ID] {
			continue
		}
		seen[is.ID] = true
		hunk := l.fixHunk(is)
		if hunk == "" {
			continue
		}
		fmt.Fprintf(&b, "## Fixed here before: %s {#lesson-%s}\nseverity: %s\ncategory: %s\ntags: %s %s lesson fixed\nsee: %s\n\n",
			is.Title, is.ID, orDefault(is.Severity, "medium"), orDefault(is.Category, "bug"), is.Ref, filepath.Base(is.Path), orDefault(is.Ref, "model finding"))
		fmt.Fprintf(&b, "In this repository this was found in %s (introduced in %s by %s) and fixed in %s by %s (%q). %s\n\n",
			filepath.Base(is.Path), shortSHA(is.FirstSeen), orDefault(is.FirstBy, "someone"), shortSHA(is.FixedIn), orDefault(is.FixedBy, "someone"),
			is.FixedMsg, oneSentence(is.Detail))
		b.WriteString("```diff\n" + hunk + "```\n\n")
		n++
	}
	for _, ig := range l.ignores.All() {
		if n >= maxLessons {
			break
		}
		if ig.Scope == "commit" || ig.Snippet == "" && ig.Scope == "code" {
			continue
		}
		id := "dismissed-" + ig.ID
		if seen[id] {
			continue
		}
		seen[id] = true
		where := "everywhere in this repository"
		if ig.Scope == "code" {
			where = "on this code"
		} else if len(ig.Paths) > 0 {
			where = "under " + strings.Join(ig.Paths, ", ")
		}
		fmt.Fprintf(&b, "## Judged not a problem here: %s {#%s}\nseverity: info\ncategory: %s\ntags: %s %s dismissed false positive intentional\n\n",
			orDefault(ig.Title, ig.Key), id, orDefault(ig.Category, "design"), ig.Key, strings.Join(ig.Paths, " "))
		fmt.Fprintf(&b, "The team dismissed this kind of finding %s", where)
		if ig.Reason != "" {
			fmt.Fprintf(&b, ": %q", ig.Reason)
		}
		b.WriteString(". Do not report it again for code like this unless it is clearly a different, real defect.\n")
		if ig.Snippet != "" {
			b.WriteString("\n```java\n" + strings.TrimSpace(ig.Snippet) + "\n```\n")
		}
		b.WriteString("\n")
		n++
	}

	path := filepath.Join(l.dir, "lessons.md")
	if old, err := os.ReadFile(path); err == nil && string(old) == b.String() {
		return n, nil
	}
	if n == 0 {
		_ = os.Remove(path)
		return 0, nil
	}
	if err := os.MkdirAll(l.dir, 0o755); err != nil {
		return n, err
	}
	return n, os.WriteFile(path, []byte(b.String()), 0o644)
}

// fixHunk is the part of the fixing commit's diff that removed the flagged line.
func (l *Lessons) fixHunk(is Issue) string {
	c, err := l.repo.Commit(is.FixedIn)
	if err != nil {
		return ""
	}
	files, err := l.repo.Diff(c)
	if err != nil {
		return ""
	}
	want := normalizeCode(is.Snippet)
	for _, f := range files {
		if f.Path != is.Path && f.OldPath != is.Path {
			continue
		}
		var hunk []string
		found := false
		for _, line := range strings.Split(f.Patch, "\n") {
			if strings.HasPrefix(line, "@@") {
				if found {
					break
				}
				hunk = hunk[:0]
				continue
			}
			if strings.HasPrefix(line, "diff ") || strings.HasPrefix(line, "---") || strings.HasPrefix(line, "+++") || strings.HasPrefix(line, "index ") {
				continue
			}
			hunk = append(hunk, line)
			if strings.HasPrefix(line, "-") && want != "" && normalizeCode(line[1:]) == want {
				found = true
			}
		}
		if found {
			if len(hunk) > 24 {
				hunk = hunk[:24]
			}
			return strings.TrimRight(strings.Join(hunk, "\n"), "\n") + "\n"
		}
	}
	// The fix was elsewhere (a constant's value, another file): show that commit's first change.
	for _, f := range files {
		if strings.HasSuffix(f.Path, ".java") && f.Patch != "" {
			var out []string
			for _, line := range strings.Split(f.Patch, "\n") {
				if strings.HasPrefix(line, "+") || strings.HasPrefix(line, "-") || strings.HasPrefix(line, " ") {
					if !strings.HasPrefix(line, "+++") && !strings.HasPrefix(line, "---") {
						out = append(out, line)
					}
				}
				if len(out) == 16 {
					break
				}
			}
			if len(out) > 0 {
				return "# " + f.Path + "\n" + strings.Join(out, "\n") + "\n"
			}
		}
	}
	return ""
}

func oneSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i > 0 {
		return s[:i+1]
	}
	return s
}
